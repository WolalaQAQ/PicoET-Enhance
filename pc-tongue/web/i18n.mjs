export function errorMessage(language, raw) {
  const key = knownErrors.find(([text]) => raw.includes(text))?.[1];
  return `${messages[language].requestError}: ${key ? `${messages[language][key]} · ` : ""}${raw}`;
}
export function preferredLanguage(languages = []) {
  return /^zh(?:-|$)/i.test(languages[0] || "") ? "zh-CN" : "en";
}
export function initialLanguage(storage, languages) {
  let saved;
  try { saved = storage?.getItem(LANGUAGE_KEY); } catch {}
  return Object.hasOwn(messages, saved) ? saved : preferredLanguage(languages);
}
